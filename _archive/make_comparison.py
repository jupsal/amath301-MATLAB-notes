"""Build a side-by-side comparison page from two versions of a chapter.

Usage:
    python3 drafts/make_comparison.py CURRENT.qmd DRAFT.qmd OUTPUT.qmd

Both files mark the start of each section with an HTML comment like
    <!-- compare: slicing -->
Sections with the same name are shown side by side. Text before the first
marker (title, reminder, learning objectives) is skipped. Sections that are
identical in both files are shown once, full width.
"""
import re
import sys

MARKER = re.compile(r"^<!--\s*compare:\s*([\w-]+)\s*-->\s*$", re.MULTILINE)


def split_sections(path):
    text = open(path, encoding="utf-8").read()
    parts = MARKER.split(text)
    # parts = [before, key1, body1, key2, body2, ...]
    keys = parts[1::2]
    bodies = parts[2::2]
    return keys, dict(zip(keys, bodies))


def clean(body):
    # Remove cross-reference ids so they aren't defined twice in the book.
    body = re.sub(r"\{#(?:sec|tbl|fig)-[\w-]+\s*\}", "", body)
    body = re.sub(r"#(?:sec|tbl|fig)-[\w-]+\s+(?=[.}])", "", body)
    body = re.sub(r"\{\s*\}", "", body)

    # Keep headings, but leave them out of the page's table of contents.
    def demote(m):
        hashes, title = m.group(1), m.group(2).rstrip()
        attrs = re.search(r"\{([^}]*)\}\s*$", title)
        if attrs:
            title = title[: attrs.start()].rstrip()
            extra = attrs.group(1).strip()
            return f"{hashes} {title} {{{extra} .unnumbered .unlisted}}"
        return f"{hashes} {title} {{.unnumbered .unlisted}}"

    out, in_code = [], False
    for line in body.strip("\n").splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        if not in_code:
            line = re.sub(r"^(#{2,6})\s+(.*)$", demote, line)
        out.append(line)
    return "\n".join(out).strip()


def first_heading(body):
    m = re.search(r"^#{2,6}\s+(.*?)\s*(\{.*\})?\s*$", body, re.MULTILINE)
    return m.group(1) if m else None


def merged_order(left_keys, right_keys):
    order = list(left_keys)
    for i, key in enumerate(right_keys):
        if key in order:
            continue
        prev = right_keys[i - 1] if i > 0 else None
        pos = order.index(prev) + 1 if prev in order else len(order)
        order.insert(pos, key)
    return order


def main(current, draft, output):
    lkeys, left = split_sections(current)
    rkeys, right = split_sections(draft)
    lines = [
        "---",
        'title: "Tone comparison: Arrays"',
        "page-layout: full",
        "toc: false",
        "number-sections: false",
        "---",
        "",
        "<!-- GENERATED by drafts/make_comparison.py. Don't edit by hand. -->",
        "",
        "::: {.compare-intro}",
        f"**Left:** the current version (`{current}`). "
        f"**Right:** the concise draft (`{draft}`). "
        "Sections are lined up by topic. Sections that are the same in both "
        "versions are shown once, full width.",
        ":::",
        "",
    ]
    empty = "*No matching section in this version.*"
    for key in merged_order(lkeys, rkeys):
        lbody = clean(left.get(key, ""))
        rbody = clean(right.get(key, ""))
        lh = first_heading(left.get(key, ""))
        rh = first_heading(right.get(key, ""))
        if lh and rh and lh != rh:
            label = f"{lh} / {rh}"
        else:
            label = lh or rh or key
        lines.append(f'## {label} {{.compare-section}}')
        lines.append("")
        if lbody and lbody == rbody:
            lines += ["::: {.compare-same}", "*Same in both versions.*", ":::", "", lbody, ""]
            continue
        lines += [
            ":::::: {.columns .compare-row}",
            '::::: {.column width="49%" .compare-current}',
            "",
            lbody or empty,
            "",
            ":::::",
            '::::: {.column width="2%"}',
            ":::::",
            '::::: {.column width="49%" .compare-concise}',
            "",
            rbody or empty,
            "",
            ":::::",
            "::::::",
            "",
        ]
    open(output, "w", encoding="utf-8").write("\n".join(lines))
    print(f"Wrote {output} ({len(merged_order(lkeys, rkeys))} sections)")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
